// Builds twilight.json (read by Salla) from src/schema: base.json + settings/*.json + components/*.json.
// Missing `key`s get stable UUIDs derived from the component path and field id, so edits never reshuffle them.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dir = (p) => join(root, 'src/schema', p);
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const uuid = (seed) => {
  const h = createHash('sha1').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
function keyed(fields, scope) {
  return fields.map((f) => {
    const out = { ...f };
    if (!out.key && out.type !== 'static') out.key = uuid(`${scope}:${out.id}`);
    if (out.fields) out.fields = keyed(out.fields, `${scope}:${out.id}`);
    if (Array.isArray(out.options)) out.options = out.options.map((o) => ({ ...o, key: o.key || uuid(`${scope}:${out.id}:${o.value}`) }));
    if (Array.isArray(out.selected)) out.selected = out.selected.map((o) => ({ ...o, key: o.key || uuid(`${scope}:${out.id}:${o.value}`) }));
    return out;
  });
}
const files = (p) => readdirSync(dir(p)).filter((f) => f.endsWith('.json')).sort();
const settings = files('settings').flatMap((f) => read(join(dir('settings'), f)));
const components = files('components').map((f) => read(join(dir('components'), f)))
  .sort((a, b) => (a.order ?? 999) - (b.order ?? 999))
  .map(({ order, ...c }) => ({ ...c, key: c.key || uuid(c.path), fields: keyed(c.fields || [], c.path) }));
const ids = new Set();
for (const c of components) { if (ids.has(c.path)) throw new Error(`duplicate component ${c.path}`); ids.add(c.path); }
const out = { ...read(dir('base.json')), settings: keyed(settings, 'settings'), components };
writeFileSync(join(root, 'twilight.json'), JSON.stringify(out, null, 2) + '\n');
// Index files so new components only need their own .scss/.js files.
const listDir = (p, ext) => { try { return readdirSync(join(root, p)).filter((f) => f.endsWith(ext)).sort(); } catch { return []; } };
writeFileSync(join(root, 'src/assets/styles/06-wareef/_components.scss'),
  '// Generated by tools/build-twilight.mjs\n' + listDir('src/assets/styles/06-wareef/components', '.scss').map((f) => `@import './components/${f.replace(/^_/, '').replace(/\.scss$/, '')}';`).join('\n') + '\n');
writeFileSync(join(root, 'src/assets/js/wareef/components.js'),
  '// Generated by tools/build-twilight.mjs\n' + listDir('src/assets/js/wareef/components', '.js').map((f) => `import './components/${f}';`).join('\n') + '\n');
console.log(`twilight.json: ${settings.length} settings, ${components.length} custom components`);
